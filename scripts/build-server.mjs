// Builds server/submit-run/core.js from the game's own <script id="core"> so the server scores runs with exactly the
// same rules as the browser. Run after any change to the core:  node scripts/build-server.mjs
import fs from "fs";
const html = fs.readFileSync(new URL("../index.html", import.meta.url), "utf8");
const core = /<script id="core">([\s\S]*?)<\/script>/.exec(html)[1];
const out = `// GENERATED by scripts/build-server.mjs from index.html — do not edit by hand.
${core}
const dayPuzzle = d => variant(puzzleForDay(d), "normal", null, packForDay(d));
const modePuzzle = d => variant(puzzleForDay(d + 4), modeForDay(d), pickForDay(d), packForDay(d + 5));
export { CONFIG, LANES, CHORDS, lanesOf, dayNumber, dayPuzzle, modePuzzle, scoreRun, realPool, realOf, realWeights };
`;
fs.writeFileSync(new URL("../server/submit-run/core.js", import.meta.url), out);
console.log(`wrote server/submit-run/core.js (${(out.length / 1024).toFixed(0)} KB)`);

// One-file version for pasting into the Supabase Dashboard editor (Edge Functions → Deploy new function → Via editor).
const logic = fs.readFileSync(new URL("../server/submit-run/logic.js", import.meta.url), "utf8").replace(/^import .*$/m, "").replace(/^export \{ CONFIG \};$/m, "").replace(/^export /gm, "");
const index = fs.readFileSync(new URL("../server/submit-run/index.ts", import.meta.url), "utf8").replace(/^import \{ puzzleFor.*$/m, "");
const bundle = `// GENERATED by scripts/build-server.mjs — paste this whole file as index.ts of the "submit-run" Edge Function.\n// @ts-nocheck\n${core}\nconst dayPuzzle = d => variant(puzzleForDay(d), "normal", null, packForDay(d));\nconst modePuzzle = d => variant(puzzleForDay(d + 4), modeForDay(d), pickForDay(d), packForDay(d + 5));\n${logic}\n${index}`;
fs.writeFileSync(new URL("../server/submit-run.bundle.ts", import.meta.url), bundle);
console.log(`wrote server/submit-run.bundle.ts (${(bundle.length / 1024).toFixed(0)} KB)`);
